#: Words the prose walks through, which the page should always offer.
FEATURED = ["firefighter", "newsletter", "sunflower"]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=PROJECT_ROOT / "docs" / "assets" / "tokens.js",
        help="where to write the page data",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    tokenizer = load_tokenizer()
    groups = build_groups(tokenizer, load_compounds())
    group_of = {
        word: name for name, words in groups.as_dict().items() for word in words
    }

    entries = []
    for word in list(MEASURED) + [w for w in FEATURED if w not in MEASURED]:
        bare, spaced = tokenize_both_ways(tokenizer, word)
        entries.append(
            {
                "word": word,
                "group": group_of.get(word, "unlisted"),
                "bare": bare,
                "spaced": spaced,
                "activation": MEASURED.get(word),
            }
        )

    entries.sort(key=lambda e: (e["group"], -(e["activation"] or -1), e["word"]))

    payload = {
        "model": tokenizer.name_or_path,
        "feature": 118230,
        "layer": 0,
        "featured": FEATURED,
        "words": entries,
    }

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as handle:
        handle.write("// Generated by scripts/build_page_data.py — do not edit.\n")
        handle.write("window.TOKEN_DATA = ")
        json.dump(payload, handle, indent=2, ensure_ascii=False)
        handle.write(";\n")

    measured = sum(1 for e in entries if e["activation"] is not None)
    print(f"Wrote {args.output} — {len(entries)} words, {measured} with activations")


if __name__ == "__main__":
    main()
