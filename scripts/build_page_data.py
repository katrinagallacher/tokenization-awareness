#!/usr/bin/env python3
"""Generate the token data the write-up's inspector runs on.

The page lets a reader pick a compound and see how Qwen3-4B actually splits it,
with and without a leading space, next to the activation the feature gave it.
Those tokenizations are computed here rather than typed by hand, so the page
cannot drift from the tokenizer.

Activation values come from the committed reference run; only words that were
actually measured are included.

    python scripts/build_page_data.py
"""

from __future__ import annotations

import sys
from pathlib import Path

# Allow running straight from a clone, without `pip install -e .`
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import argparse  # noqa: E402
